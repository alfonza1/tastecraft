import { AXES, tokens, type Profile } from "./model";
import { tasteCardSvg } from "./tasteCard";
export type ExportKind = "skill" | "css" | "json" | "component" | "card";
export const EXPORTS: {
  id: ExportKind;
  label: string;
  filename: string;
  type: string;
}[] = [
  {
    id: "card",
    label: "Taste card",
    filename: "tastecraft.svg",
    type: "image/svg+xml",
  },
  {
    id: "skill",
    label: "Agent skill",
    filename: "SKILL.md",
    type: "text/markdown",
  },
  {
    id: "css",
    label: "CSS tokens",
    filename: "tastecraft.css",
    type: "text/css",
  },
  {
    id: "json",
    label: "Profile JSON",
    filename: "tastecraft.json",
    type: "application/json",
  },
  {
    id: "component",
    label: "React component",
    filename: "TastecraftCard.tsx",
    type: "text/plain",
  },
];
export function cssExport(profile: Profile): string {
  return `/* Generated by Tastecraft. Scope these tokens to your app or component. */\n:root {\n${Object.entries(
    tokens(profile.values),
  )
    .map(([key, value]) => `  ${key}: ${value};`)
    .join(
      "\n",
    )}\n}\n\n@media (prefers-reduced-motion: reduce) {\n  :root { --tc-duration: 0ms; --tc-lift: 0px; }\n}\n`;
}
export function skillExport(profile: Profile): string {
  const title = profile.name.replace(/[\r\n]/g, " ");
  return `---\nname: tastecraft-design\ndescription: Apply this project's human-selected design preferences to interface work.\n---\n\n# Design direction: ${title}\n\nThis profile was explicitly selected in Tastecraft. It is project-specific guidance, not a model trained on the user.\n\n## Preferences\n\n${AXES.map(
    (axis) => {
      const count = profile.history.filter(
        (choice) => choice.axis === axis.id && choice.value !== null,
      ).length;
      return `- **${axis.title}:** ${profile.values[axis.id]}/100 (${axis.low} → ${axis.high}). ${count} recorded comparison${count === 1 ? "" : "s"}; values may include manual refinement.`;
    },
  ).join(
    "\n",
  )}\n\n## Implementation\n\nUse the exported tastecraft.css variables and TastecraftCard.tsx as concrete references. Preserve semantic HTML, visible keyboard focus, readable contrast, and prefers-reduced-motion. Adapt layout to the product; do not copy the sample task content. Ask before changing the direction substantially. These five axes are a starting point, not a complete design system.\n\n## Tokens\n\n\x60\x60\x60css\n${cssExport(profile)}\x60\x60\x60\n`;
}
export function componentExport(profile: Profile): string {
  const styles = `${cssExport(profile).replaceAll(":root", ".tastecraft-card")}\n.tastecraft-card { font-family: var(--tc-font-body); color: var(--tc-text); background: var(--tc-surface); border: 1px solid var(--tc-border); border-radius: var(--tc-radius); padding: var(--tc-space); max-width: 420px; }\n.tastecraft-card h2 { font-family: var(--tc-font-heading); margin-top: 0; }\n.tastecraft-card button { font: inherit; padding: 10px 16px; color: white; background: var(--tc-accent); border: 0; border-radius: var(--tc-radius); cursor: pointer; transition: transform var(--tc-duration); }\n.tastecraft-card button:hover { transform: translateY(calc(-1 * var(--tc-lift))); }\n.tastecraft-card button:focus-visible { outline: 3px solid var(--tc-accent); outline-offset: 4px; }`;
  return `import { useState } from 'react';\n\n// Standalone reference component. Requires React; no styling dependencies.\nconst styles = ${JSON.stringify(styles)};\n\nexport default function TastecraftCard() {\n  const [done, setDone] = useState(false);\n  return (\n    <section className="tastecraft-card" aria-label="Task">\n      <style>{styles}</style>\n      <h2>Make something yours.</h2>\n      <p>A small, working reference for your project's visual direction.</p>\n      <button type="button" aria-pressed={done} onClick={() => setDone(!done)}>\n        {done ? 'Completed ✓' : 'Mark complete'}\n      </button>\n    </section>\n  );\n}\n`;
}
export function exportContent(profile: Profile, kind: ExportKind): string {
  if (kind === "card") return tasteCardSvg(profile);
  if (kind === "css") return cssExport(profile);
  if (kind === "skill") return skillExport(profile);
  if (kind === "component") return componentExport(profile);
  return (
    JSON.stringify(
      { ...profile, name: profile.name.trim() || "Untitled project" },
      null,
      2,
    ) + "\n"
  );
}
export function downloadFile(
  content: string | Blob,
  filename: string,
  type: string,
) {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
